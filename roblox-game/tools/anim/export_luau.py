"""out/<Clip>/resolved.json (what r6_clip.py rendered) -> src/shared/R6Clips.luau.

  python export_luau.py

Each pose is the exact Motor6D.Transform r6_clip.py rendered (12 numbers: x, y, z, r00..r22), so the
game plays what the contact sheets show. Easing belongs to the key a segment STARTS from, as in the
render and in Roblox's own KeyframeSequence.
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "src", "shared", "R6Clips.luau")
meta = json.load(open(os.path.join(HERE, "clips", "_meta.json"), encoding="utf-8-sig"))


def n(v):
    s = ("%.5f" % v).rstrip("0").rstrip(".")
    return "0" if s in ("", "-0") else s


lines = [
    "-- GENERATED by tools/anim/export_luau.py from the Blender renders in tools/anim/out. Do not edit:",
    "-- change tools/anim/gen_clips.py, re-render with r6_clip.py, then run export_luau.py.",
    "--",
    "-- R6 clips as Motor6D.Transform keyframes: pose[joint] = { x, y, z, r00, r01, r02, r10, r11, r12, r20, r21, r22 }.",
    "-- ease is the curve of the segment that STARTS at that key.",
    "",
    "return {",
]
for name in sorted(meta):
    m = meta[name]
    res = json.load(open(os.path.join(HERE, "out", name, "resolved.json")))
    lines.append(f"\t{name} = {{")
    lines.append(f"\t\ttransform = true,")
    lines.append(f"\t\tlength = {n(m['length'])},")
    lines.append(f"\t\tloop = {'true' if m['loop'] else 'false'},")
    lines.append(f"\t\tfadeIn = {n(m['fadeIn'])},")
    lines.append(f"\t\tfadeOut = {n(m['fadeOut'])},")
    lines.append(f"\t\tpriority = {m['priority']},")
    joints = sorted(res["keys"][0]["poses"])
    lines.append("\t\tjoints = { " + ", ".join(f'"{j}"' for j in joints) + " },")
    lines.append("\t\tkeys = {")
    for k in res["keys"]:
        lines.append(f'\t\t\t{{ t = {n(k["t"])}, ease = "{k["ease"]}", pose = {{')
        for j in joints:
            p = k["poses"][j]
            vals = list(p["pos"]) + [x for row in p["rows"] for x in row]
            lines.append(f'\t\t\t\t["{j}"] = {{ ' + ", ".join(n(v) for v in vals) + " },")
        lines.append("\t\t\t} },")
    lines.append("\t\t},")
    lines.append("\t},")
lines.append("}")
open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
print("wrote", os.path.normpath(OUT), "clips:", len(meta))
