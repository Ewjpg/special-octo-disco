"""tools/anim/baked/*.json (baked in Blender by rbx_bake.py) -> src/shared/R6Clips/ (one module per clip).

  python tools/anim/export_luau.py

Every key is the exact Motor6D.Transform the Blender rig produced on that frame (sampled at 30 fps
from the 60 fps Bezier curves), so the game plays the same smooth motion; keys are dense, so the
game interpolates linearly between them. A pose is { x, y, z, qx, qy, qz, qw } (position + quaternion),
which keeps every module well under Studio's 200k-character script limit.
"""
import json, os, glob, math

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.join(HERE, "..", "..", "src", "shared", "R6Clips")
BAKED = os.path.join(HERE, "baked")
meta = json.load(open(os.path.join(BAKED, "_meta.json")))


def n(v, digits=4):
    s = (f"%.{digits}f" % v).rstrip("0").rstrip(".")
    return "0" if s in ("", "-0") else s


def quat(r):
    # rotation matrix (row-major 3x3) -> quaternion (x, y, z, w)
    m00, m01, m02, m10, m11, m12, m20, m21, m22 = r
    tr = m00 + m11 + m22
    if tr > 0:
        s = math.sqrt(tr + 1.0) * 2
        w, x, y, z = 0.25 * s, (m21 - m12) / s, (m02 - m20) / s, (m10 - m01) / s
    elif m00 > m11 and m00 > m22:
        s = math.sqrt(1.0 + m00 - m11 - m22) * 2
        w, x, y, z = (m21 - m12) / s, 0.25 * s, (m01 + m10) / s, (m02 + m20) / s
    elif m11 > m22:
        s = math.sqrt(1.0 + m11 - m00 - m22) * 2
        w, x, y, z = (m02 - m20) / s, (m01 + m10) / s, 0.25 * s, (m12 + m21) / s
    else:
        s = math.sqrt(1.0 + m22 - m00 - m11) * 2
        w, x, y, z = (m10 - m01) / s, (m02 + m20) / s, (m12 + m21) / s, 0.25 * s
    if w < 0:
        x, y, z, w = -x, -y, -z, -w
    return x, y, z, w


os.makedirs(OUT_DIR, exist_ok=True)
for old in glob.glob(os.path.join(OUT_DIR, "*.luau")):
    os.remove(old)
old_single = os.path.join(HERE, "..", "..", "src", "shared", "R6Clips.luau")
if os.path.exists(old_single):
    os.remove(old_single)

HEADER = ("-- GENERATED by tools/anim/export_luau.py from the clips animated in Blender (tools/anim/R6Football.blend,\n"
          "-- keyed by tools/anim/author_clips.py, baked by rbx_bake.py). Do not edit by hand.\n")
total = 0
for name in sorted(meta):
    m = meta[name]
    res = json.load(open(os.path.join(BAKED, name + ".json")))
    joints = sorted(res["keys"][0]["pose"])
    lines = [HEADER, "return {", "\ttransform = true,", f"\tlength = {n(res['length'])},",
             f"\tloop = {'true' if m['loop'] else 'false'},", f"\tfadeIn = {n(m['fadeIn'])},",
             f"\tfadeOut = {n(m['fadeOut'])},", f"\tpriority = {m['priority']},",
             "\tjoints = { " + ", ".join(f'"{j}"' for j in joints) + " },", "\tkeys = {"]
    for k in res["keys"]:
        parts = []
        for j in joints:
            v = k["pose"][j]
            q = quat(v[3:])
            parts.append(f'["{j}"] = {{ ' + ", ".join([n(x, 3) for x in v[:3]] + [n(x, 4) for x in q]) + " }")
        lines.append(f'\t\t{{ t = {n(k["t"])}, pose = {{ ' + ", ".join(parts) + " } },")
    lines += ["\t},", "}"]
    path = os.path.join(OUT_DIR, name + ".luau")
    open(path, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    total += os.path.getsize(path)

init = [HEADER, "-- Every child module is one clip; this table maps clip name -> clip.", "local clips = {}",
        "for _, child in ipairs(script:GetChildren()) do",
        '\tif child:IsA("ModuleScript") then', "\t\tclips[child.Name] = require(child) :: any", "\tend", "end",
        "return clips"]
open(os.path.join(OUT_DIR, "init.luau"), "w", encoding="utf-8", newline="\n").write("\n".join(init) + "\n")
print("wrote", len(meta), "clips to", os.path.normpath(OUT_DIR), "total bytes", total)
